#!/usr/bin/env python3
"""Generate the TTL snippets FROM the validated crosswalk.csv. Agents never write TTL.

  snippets/proposed-artifacts.ttl        — new owl:Class declarations under existing parents
  snippets/aml-artifact-restrictions.ttl — subClassOf owl:Restriction rows on :AML.T#### classes
  snippets/aml-annex-restrictions.ttl    — restrictions for the v2026.06 annex techniques,
                                           emitted from crosswalk-annex-v2026.06.csv when it
                                           exists (upstream #611, merged 2026-07-15, gave the
                                           annex techniques IRIs; verified 2026-07-24)

All are parse-validated with rdflib before this script exits.
"""
import csv
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

PROJ = Path(__file__).resolve().parent.parent
SNIP = PROJ / "snippets"

PREFIX = """@prefix : <http://d3fend.mitre.org/ontologies/d3fend.owl#> .
@prefix owl: <http://www.w3.org/2002/07/owl#> .
@prefix rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix d3f: <http://d3fend.mitre.org/ontologies/d3fend.owl#> .
"""

ESC = str.maketrans({'"': '\\"', "\\": "\\\\", "\n": " "})


def lit(s):
    return '"' + re.sub(r"\s+", " ", (s or "").strip()).translate(ESC) + '"'


def local(iri):
    return iri.split(":", 1)[1] if ":" in iri else iri


def emit_rebaseline():
    """2026-11: one snippet from crosswalk-rebaseline-2026-11.csv (the queue after re-adjudication).

    Includes every non-retired queued row on a technique that still exists in ATLAS latest (moved
    techniques are excluded: their successor IDs have no IRI until the next ATLAS ingest). Open-PR
    rows are included so the snippet measures the whole queue; merged #617/#618 are already on develop.
    """
    SNIP.mkdir(exist_ok=True)
    by_tech = defaultdict(list)
    for r in csv.DictReader(open(PROJ / "crosswalk-rebaseline-2026-11.csv")):
        if r["verdict"] == "retire" or r["removed_in_latest"] == "True":
            continue
        by_tech[r["atlas_id"]].append(r)
    B = [PREFIX,
         "# Re-adjudicated ATLAS -> D3FEND restrictions (rebaseline 2026-11, against develop a24ebcc).",
         "# Generated by 70_emit_ttl.py --rebaseline from crosswalk-rebaseline-2026-11.csv; do not hand-edit.",
         ""]
    n = 0
    for tid in sorted(by_tech):
        seen, parts = set(), []
        for r in sorted(by_tech[tid], key=lambda x: (x["verb"], x["artifact_iri"])):
            key = (r["verb"], r["artifact_iri"])
            if key in seen:
                continue
            seen.add(key)
            n += 1
            parts.append(f"""        [ rdf:type owl:Restriction ;
            owl:onProperty :{local(r['verb'])} ;
            owl:someValuesFrom :{local(r['artifact_iri'])} ]""")
        B.append(f":{tid} rdfs:subClassOf\n" + " ,\n".join(parts) + " .\n")
    out = SNIP / "aml-rebaseline-2026-11.ttl"
    out.write_text("\n".join(B))
    from rdflib import Graph
    g = Graph()
    g.parse(out, format="turtle")
    print(f"{out.name}: parses clean, {len(g)} triples; {n} restrictions across {len(by_tech)} techniques")


def main():
    if "--rebaseline" in sys.argv:
        return emit_rebaseline()
    SNIP.mkdir(exist_ok=True)
    rows = [r for r in csv.DictReader(open(PROJ / "crosswalk.csv")) if r["artifact_iri"]]
    fam_f = PROJ / "work" / "consolidation" / "artifact_family.json"
    family = json.load(open(fam_f))["classes"] if fam_f.exists() else []

    # ---- proposed artifact classes ----
    A = [PREFIX,
         "# Proposed AI/ML digital-artifact classes for D3FEND.",
         "# Generated by 70_emit_ttl.py from the validated crosswalk — do not hand-edit.",
         "# Each class sits under an EXISTING D3FEND parent; none replaces an existing class.",
         ""]
    for c in sorted(family, key=lambda x: x["canonical_name"]):
        A.append(f""":{c['canonical_name']} a owl:Class ;
    rdfs:label {lit(c.get('label') or re.sub(r'(?<!^)(?=[A-Z])', ' ', c['canonical_name']))} ;
    rdfs:subClassOf :{local(c['parent_iri'])} ;
    :definition {lit(c['definition'])} .
""")
    (SNIP / "proposed-artifacts.ttl").write_text("\n".join(A))

    # ---- restrictions on AML techniques ----
    by_tech = defaultdict(list)
    for r in rows:
        by_tech[r["atlas_id"]].append(r)
    B = [PREFIX,
         "# Proposed digital-artifact relations for MITRE ATLAS techniques in D3FEND.",
         "# Generated by 70_emit_ttl.py from the validated crosswalk — do not hand-edit.",
         "# Shape mirrors the existing ATT&CK pattern (cf. :T1003.001 accesses :AuthenticationService).",
         ""]
    n_rel = 0
    for tid in sorted(by_tech):
        seen, parts = set(), []
        for r in sorted(by_tech[tid], key=lambda x: (x["verb"], x["artifact_iri"])):
            key = (r["verb"], r["artifact_iri"])
            if key in seen:
                continue
            seen.add(key)
            n_rel += 1
            parts.append(f"""        [ rdf:type owl:Restriction ;
            owl:onProperty :{local(r['verb'])} ;
            owl:someValuesFrom :{local(r['artifact_iri'])} ]""")
        B.append(f":{tid} rdfs:subClassOf\n" + " ,\n".join(parts) + " .\n")
    (SNIP / "aml-artifact-restrictions.ttl").write_text("\n".join(B))

    # ---- annex restrictions (same shape; separate snippet so core and annex stay separable) ----
    emitted = ["proposed-artifacts.ttl", "aml-artifact-restrictions.ttl"]
    annex_csv = PROJ / "crosswalk-annex-v2026.06.csv"
    n_annex_rel, annex_techs = 0, {}
    if annex_csv.exists():
        a_by_tech = defaultdict(list)
        for r in csv.DictReader(open(annex_csv)):
            if r["artifact_iri"]:
                a_by_tech[r["atlas_id"]].append(r)
        C = [PREFIX,
             "# Proposed digital-artifact relations for the ATLAS v2026.06 annex techniques.",
             "# Generated by 70_emit_ttl.py from the verified annex crosswalk — do not hand-edit.",
             "# Emittable since upstream #611 (2026-07-15) ingested ATLAS v2026.06.",
             ""]
        for tid in sorted(a_by_tech):
            seen, parts = set(), []
            for r in sorted(a_by_tech[tid], key=lambda x: (x["verb"], x["artifact_iri"])):
                key = (r["verb"], r["artifact_iri"])
                if key in seen:
                    continue
                seen.add(key)
                n_annex_rel += 1
                parts.append(f"""        [ rdf:type owl:Restriction ;
            owl:onProperty :{local(r['verb'])} ;
            owl:someValuesFrom :{local(r['artifact_iri'])} ]""")
            C.append(f":{tid} rdfs:subClassOf\n" + " ,\n".join(parts) + " .\n")
        (SNIP / "aml-annex-restrictions.ttl").write_text("\n".join(C))
        annex_techs = a_by_tech
        emitted.append("aml-annex-restrictions.ttl")

    # ---- parse validation (rdflib if present; otherwise the docker acceptance test validates it) ----
    try:
        from rdflib import Graph
    except ImportError:
        print("NOTE: rdflib not importable here — skipping local parse-check. "
              "Validate the snippets in the d3fend container (80_acceptance_test.sh loads the TTL, "
              "so a syntax error will fail there).")
    else:
        for f in emitted:
            g = Graph()
            g.parse(SNIP / f, format="turtle")
            print(f"{f}: parses clean, {len(g)} triples")
    print(f"emitted: {len(family)} new classes, {n_rel} restrictions across {len(by_tech)} techniques"
          + (f", annex: {n_annex_rel} restrictions across {len(annex_techs)} techniques" if annex_techs else ""))


if __name__ == "__main__":
    main()
